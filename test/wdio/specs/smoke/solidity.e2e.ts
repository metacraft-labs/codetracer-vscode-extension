/**
 * Solidity (EVM) smoke tests for the CodeTracer VS Code extension.
 *
 * This is a custom smoke test suite for Solidity/EVM rather than using the
 * generic defineLanguageSmokeTests helper. EVM traces have specific
 * characteristics that require tailored assertions:
 *
 *   - The recorded call tree is `<toplevel> → compute() → add()`, and the
 *     calltrace names the Solidity functions (`compute`, `add`).
 *   - The session starts at the toplevel's first step (line 1), before
 *     compute() is entered, where no local is in scope. Step-overs from there
 *     reach the toplevel's call of compute() (line 10), and the next one
 *     steps over the whole call to the last step of the trace, where only
 *     the storage slots are listed; reaching compute()'s locals takes
 *     step-in.
 *   - Solidity events are recorded as raw EVM LOG payloads (the event's
 *     topic and data words) rather than decoded event names.
 *
 * The fixture trace is generated by scripts/prepare-solidity-fixture.sh.
 * It records the FlowTest.sol contract's compute() function which:
 *   - Assigns local variables a = 10, b = 20
 *   - Writes to storedA and storedResult storage slots (SSTORE)
 *   - Calls the internal add() helper
 *   - Emits a Computed event (LOG1 opcode)
 *
 * Source: codetracer-evm-recorder/contracts/FlowTest.sol
 */
import { expect } from '@wdio/globals'
import { DebugSession, EditorPane, ExtensionState, type StoppedFrame } from '../../page-objects'
import {
  assertSessionStarts,
  assertEditorLoadsFile,
  assertThreadsExist,
  assertEventsPopulated,
  assertStepWorks,
} from '../../helpers/language-smoke-helpers'
import { captureFullDiagnostics, screenshot, writeDiag } from '../../helpers/diagnostics'
import { findLocal, listLocals } from '../../helpers/locals'
import { resolveTracePath, traceExists } from '../../helpers/trace-utils'

const TRACE_NAME = 'solidity-flow-test'
const EXPECTED_FILE = 'FlowTest.sol'
const LANG_ID = 'Solidity'

// The EVM recorder now resolves source-map entries back to real
// Solidity function names (verified via ``ct-print --full`` on the
// recorder output: ``functions: ['compute', 'add']``).  The earlier
// synthetic ``fn_at_<file>:<line>`` form was a fallback that ran
// before the source-map plumbing landed -- the recorder still
// emits ``fn_at_pc_<n>`` for dispatcher orphans that the JUMP
// source-site walk can't resolve, but the user-level functions
// (compute, add for FlowTest.sol) are now surfaced verbatim.
const CALLTRACE_FUNCTION = 'compute'

// The recorder emits Solidity events as ``ioStderr`` IO records
// whose ``text`` field carries the raw LOG topic+data payload, not
// the opcode mnemonic.  For the ``Computed(uint256)`` event emitted
// by FlowTest.sol's ``compute()`` the topic is
// ``keccak256("Computed(uint256)") = 0xaccb7b7f216abc04…``.  Pin to
// that signature substring -- it's the most specific stable
// identifier of the event payload and surfaces in
// ``ct-print --full``'s IO ``text`` field verbatim.
const EVENT_LOG_TEXT = '0xaccb7b7f216abc04'

// Local variable assigned on line 11 of FlowTest.sol: `uint256 a = 10;`
// The DAP locals response lists compute()'s source-level locals beside the
// storage slots written so far (`storedA`, `storedResult`). We look for `a`
// because it is the first variable assigned in compute(), and match it by
// exact name: both storage slot names and `result` contain the letter.
const LOCAL_VAR_NAME = 'a'
const LOCAL_VAR_VALUE = '10'
// Stepping is column-aware, so line 11, `        uint256 a = 10;`, has two
// stops. `a` is first listed at the first, the declaration `uint256 a`
// (column 9), where it still holds the uint256 default 0.
const LOCAL_VAR_FIRST_LISTED = { line: 11, column: 9, frame: 'compute', value: '0' }
// At the second, the literal `10` (column 21), `a` holds 10: `a` lives in an
// EVM stack slot, and pushing the literal is what assigns it.
const LOCAL_VAR_STOP = { line: 11, column: 21, frame: 'compute' }

// Maximum step-ins to try before giving up on finding the variable. The
// loop steps in from wherever the step test left the session and checks the
// locals at each stop; `a` is listed once compute()'s body is reached.
const MAX_STEPS_FOR_LOCALS = 15

const session = new DebugSession()
const editor = new EditorPane()
const ext = new ExtensionState()

describe('CodeTracer Extension - Solidity Smoke Test', () => {
  let traceDir: string

  before(function () {
    traceDir = resolveTracePath(TRACE_NAME)
    if (!traceExists(TRACE_NAME)) {
      const message =
        `Solidity smoke tests: trace not found at ${traceDir}. ` +
        'Run scripts/prepare-solidity-fixture.sh to generate it.'
      console.warn(`SKIPPING: ${message}`)
      this.skip()
    }
  })

  afterEach(async function () {
    const testName = this.currentTest?.title?.replace(/[^a-zA-Z0-9_-]+/g, '-').substring(0, 50) ?? 'unknown'
    if (this.currentTest?.state === 'failed') {
      console.log(`[diag] Test failed: ${this.currentTest.title}`)
      await captureFullDiagnostics(`solidity-FAIL-${testName}`)
    }
    await screenshot(`solidity-${testName}`)
  })

  it('starts a debug session with the trace', async () => {
    await ext.ensureActivated()
    await assertSessionStarts(session, traceDir)

    const location = await session.currentLocation()
    console.log('[Solidity] Initial location:', JSON.stringify(location))
    writeDiag('solidity-session-start.json', { location })
  })

  it(`opens ${EXPECTED_FILE} in the editor`, async () => {
    await assertEditorLoadsFile(editor, EXPECTED_FILE)
  })

  it('reports at least one DAP thread', async () => {
    await assertThreadsExist(session)
  })

  it('loads events from the trace', async () => {
    await assertEventsPopulated(session)
  })

  it(`finds "${CALLTRACE_FUNCTION}" in the calltrace`, async () => {
    const result = await session.loadCalltrace({ depth: 50, height: 200 })
    if (result.ok && result.data) {
      const dataStr = JSON.stringify(result.data)
      writeDiag('calltrace.json', result.data)
      expect(dataStr).toContain(CALLTRACE_FUNCTION)
    } else {
      console.warn('Calltrace did not return inline data:', result.error)
      expect(result.ok).toBe(true)
    }
  })

  it('can step-over and remain in the trace', async () => {
    await assertStepWorks(session)
  })

  it(`finds ${LOCAL_VAR_NAME} in local variables after stepping`, async () => {
    // Step in until the locals list a variable named exactly `a` (not merely
    // a name containing the letter, nor the letter anywhere in the serialized
    // response) holding 10, then require where that happened and where `a`
    // was first listed. Step-in, not step-over: stepping over from the
    // toplevel steps over compute() and never stops where `a` is in scope.
    type Sighting = { step: number; value: string; stop: StoppedFrame }
    let firstListed: Sighting | null = null
    let found: Sighting | null = null
    let lastLocals: unknown = null

    for (let i = 0; i < MAX_STEPS_FOR_LOCALS; i++) {
      await session.stepIn(500)

      const result = await session.loadLocals({ lang: LANG_ID, countBudget: 100, depthLimit: 3 })
      if (!result.ok || !result.data) {
        throw new Error(`Locals request failed at step ${i + 1}: ${result.error ?? 'no inline data'}`)
      }
      lastLocals = result.data
      const stop = await session.currentStop()
      console.log(`[Solidity] Step ${i + 1}: line ${stop.line}, column ${stop.column} in ${stop.frame}, ` +
        `locals: ${JSON.stringify(listLocals(result.data))}`)
      const local = findLocal(result.data, LOCAL_VAR_NAME)
      if (!local) {
        continue
      }
      const sighting = { step: i + 1, value: local.value, stop }
      firstListed ??= sighting
      if (local.value === LOCAL_VAR_VALUE) {
        found = sighting
        console.log(`[Solidity] Found ${LOCAL_VAR_NAME} = ${local.value} at step ${i + 1}`)
        writeDiag('locals.json', { firstListed, found, locals: result.data })
        break
      }
    }

    if (!found) {
      writeDiag('locals-last.json', { firstListed, lastLocals })
      throw new Error(
        `No local named exactly "${LOCAL_VAR_NAME}" held ${LOCAL_VAR_VALUE} within ${MAX_STEPS_FOR_LOCALS} steps ` +
        `(first listed: ${JSON.stringify(firstListed)}; last response: ${JSON.stringify(lastLocals)})`,
      )
    }
    expect(found.stop.file).toContain(EXPECTED_FILE)
    expect({ line: found.stop.line, column: found.stop.column, frame: found.stop.frame })
      .toEqual(LOCAL_VAR_STOP)
    expect(firstListed.stop.file).toContain(EXPECTED_FILE)
    expect({
      line: firstListed.stop.line,
      column: firstListed.stop.column,
      frame: firstListed.stop.frame,
      value: firstListed.value,
    }).toEqual(LOCAL_VAR_FIRST_LISTED)
  })

  it(`event log contains ${EVENT_LOG_TEXT}`, async () => {
    const result = await session.loadEvents()
    if (result.ok && result.data) {
      const dataStr = JSON.stringify(result.data)
      writeDiag('events.json', result.data)
      expect(dataStr).toContain(EVENT_LOG_TEXT)
    } else {
      console.warn('Events did not return inline data:', result.error)
      expect(result.ok).toBe(true)
    }
  })

  after(async () => {
    await captureFullDiagnostics('solidity-final')
    try { await session.removeAllBreakpoints() } catch { /* ignore */ }
    try { await session.stop() } catch { /* ignore */ }
  })
})
